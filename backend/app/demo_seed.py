def _add_money_snapshots(manifest: dict[str, list[dict]]) -> None:
    """Keep explicit demo seeding representative of current production writes."""
    currency = SS_TENANT.default_currency
    products = {product["id"]: product for product in manifest["products"]}
    companies = {company["id"]: company for company in manifest["companies"]}
    for product in products.values():
        product["currency"] = currency
        for field in ("standardPrice", "salesFloor", "absoluteFloor", "cost", "b2cPrice"):
            product[f"{field}Minor"] = to_minor(product[field])
        for tier in product.get("discountTiers", []):
            tier.update({"priceMinor": to_minor(tier["price"]), "currency": currency})
        for tier in product.get("b2cTiers", []):
            tier.update({"priceMinor": to_minor(tier["price"]), "currency": currency})
    for customer_price in manifest["customer_prices"]:
        customer_price.update({"priceMinor": to_minor(customer_price["price"]), "currency": currency})
    for promotion in manifest["pricing_promotions"]:
        promotion.update({"priceMinor": to_minor(promotion["price"]), "currency": currency})
    for collection in ("offers", "orders"):
        for document in manifest[collection]:
            snapshots = [
                product_item_snapshot(
                    products[item["productId"]], quantity=item["qty"],
                    unit_price_minor=to_minor(item["price"]), currency=currency,
                    price_source="demo_snapshot",
                )
                for item in document["items"]
            ]
            company = companies[document["companyId"]]
            document.update({
                "items": snapshots,
                "currency": currency,
                "netTotalMinor": items_total_minor(snapshots, currency=currency),
                "snapshotVersion": 1,
                "companySnapshot": {
                    "companyId": company["id"], "name": company.get("name", ""),
                    "email": company.get("email", ""), "vatId": company.get("vatId", ""),
                    "city": company.get("city", ""),
                },
                "salesAttribution": {"actorUserId": document["createdBy"]},
            })
    for contract in manifest["contracts"]:
        contract.update({
            "currency": currency,
            "priceMinor": to_minor(contract["price"]),
            "machineRateMinor": to_minor(contract["machineRate"]),
            "serviceRateMinor": to_minor(contract["serviceRate"]),
        })
    for invoice in manifest["invoices"]:
        invoice.update({"currency": currency, "amountMinor": to_minor(invoice["amount"])})
    for machine in manifest["machines"]:
        machine.update({"currency": currency, "priceMinor": to_minor(machine["price"])})
    for subscription in manifest["subscriptions"]:
        snapshots = [
            product_item_snapshot(
                products[item["productId"]], quantity=item["qty"],
                unit_price_minor=to_minor(item["price"]), currency=currency,
                price_source="customer_price",
            )
            for item in subscription["items"]
        ]
        subscription.update({"items": snapshots, "currency": currency, "snapshotVersion": 1})
    for shop_order in manifest["shop_orders"]:
        snapshots = [
            product_item_snapshot(
                products[item["productId"]], quantity=item["qty"],
                unit_price_minor=to_minor(item["price"]), currency=currency,
                price_source="b2c_quantity_tier",
            )
            for item in shop_order["items"]
        ]
        for item in snapshots:
            item.pop("costMinor", None)
            item["name"] = item["productName"]
            item["taxMinor"] = 469
        shop_order.update({
            "items": snapshots, "currency": currency, "snapshotVersion": 1,
            "subtotalMinor": to_minor(shop_order["subtotal"]),
            "shippingMinor": to_minor(shop_order["shipping"]),
            "totalMinor": to_minor(shop_order["total"]),
        })


def _strict_equal(actual, expected) -> bool:
    if type(actual) is not type(expected):
        return False
    if isinstance(expected, Mapping):
        return set(actual) == set(expected) and all(
            _strict_equal(actual[key], value) for key, value in expected.items()
        )
    if isinstance(expected, list):
        return len(actual) == len(expected) and all(
            _strict_equal(actual_item, expected_item)
            for actual_item, expected_item in zip(actual, expected)
        )
    return actual == expected


def _validate_manifest(manifest: Mapping[str, list[Mapping]]) -> None:
    expected_collections = TENANT_SCOPED_COLLECTIONS | GLOBAL_SEED_COLLECTIONS
    if set(manifest) != expected_collections:
        raise DemoSeedConfigurationError("Demo manifest contains an unexpected collection set")

    for collection, documents in manifest.items():
        for document in documents:
            tenant_id = document.get("tenantId")
            if collection in TENANT_SCOPED_COLLECTIONS:
                if tenant_id != SS_TENANT_ID:
                    raise DemoSeedConfigurationError(
                        f"Demo manifest {collection} document has an invalid tenantId"
                    )
            elif "tenantId" in document:
                raise DemoSeedConfigurationError(
                    f"Global demo collection {collection} must not contain tenantId"
                )

    users = {document["id"] for document in manifest["users"]}
    companies = {document["id"] for document in manifest["companies"]}
    products = {document["id"] for document in manifest["products"]}

    def require(reference: str, targets: set[str], source: str) -> None:
        if reference not in targets:
            raise DemoSeedConfigurationError(
                f"Demo manifest reference {source} points outside the S&S tenant manifest"
            )

    for document in manifest["users"]:
        if document.get("companyId"):
            require(document["companyId"], companies, "users.companyId")
        if document.get("salesRepId"):
            require(document["salesRepId"], users, "users.salesRepId")
    membership_users: set[str] = set()
    for document in manifest["tenant_memberships"]:
        require(document["userId"], users, "tenant_memberships.userId")
        if document["userId"] in membership_users:
            raise DemoSeedConfigurationError(
                "Demo manifest contains duplicate tenant memberships"
            )
        membership_users.add(document["userId"])
        if document["role"] not in {"admin", "sales", "customer"}:
            raise DemoSeedConfigurationError("Demo membership has an invalid role")
        if document["status"] != "active":
            raise DemoSeedConfigurationError("Demo membership must be active")
        company_id = document.get("companyId")
        if document["role"] == "customer":
            require(company_id, companies, "tenant_memberships.companyId")
        elif company_id is not None:
            raise DemoSeedConfigurationError(
                "Only a customer demo membership may reference a company"
            )
    if membership_users != users:
        raise DemoSeedConfigurationError(
            "Every internal demo identity must have one tenant membership"
        )
    for document in manifest["companies"]:
        require(document["assignedSalesRepId"], users, "companies.assignedSalesRepId")
    for document in manifest["customer_prices"]:
        require(document["companyId"], companies, "customer_prices.companyId")
        require(document["productId"], products, "customer_prices.productId")
    for document in manifest["pricing_promotions"]:
        if document.get("companyId") is not None:
            require(document["companyId"], companies, "pricing_promotions.companyId")
        require(document["productId"], products, "pricing_promotions.productId")
    for collection in ("offers", "orders"):
        for document in manifest[collection]:
            require(document["companyId"], companies, f"{collection}.companyId")
            require(document["createdBy"], users, f"{collection}.createdBy")
            for item in document["items"]:
                require(item["productId"], products, f"{collection}.items.productId")
    for document in manifest["contracts"]:
        require(document["companyId"], companies, "contracts.companyId")
        require(document["productId"], products, "contracts.productId")
    for document in manifest["invoices"]:
        require(document["companyId"], companies, "invoices.companyId")
    for document in manifest["subscriptions"]:
        require(document["companyId"], companies, "subscriptions.companyId")
        require(document["createdBy"], users, "subscriptions.createdBy")
        for item in document["items"]:
            require(item["productId"], products, "subscriptions.items.productId")
    machine_ids = {document["id"] for document in manifest["machines"]}
    for document in manifest["machine_requests"]:
        require(document["machineId"], machine_ids, "machine_requests.machineId")
        customer = document.get("customer") or {}
        require(customer.get("userId"), users, "machine_requests.customer.userId")
        if customer.get("companyId") is not None:
            require(customer["companyId"], companies, "machine_requests.customer.companyId")
        for product_id in (
            document.get("requestedCoffeeProductId"),
            (document.get("terms") or {}).get("productId"),
        ):
            if product_id is not None:
                require(product_id, products, "machine_requests.productId")
    for document in manifest["shop_orders"]:
        if document.get("pricingContext") != "b2c":
            raise DemoSeedConfigurationError("Demo shop order must use B2C pricing context")
        for item in document["items"]:
            require(item["productId"], products, "shop_orders.items.productId")


def _identity_query(collection: str, document: Mapping) -> dict:
    if collection == "users":
        return {"$or": [
            {"_id": document["_id"]},
            {"id": document["id"]},
            {"email": document["email"]},
        ]}
    if collection == "customer_prices":
        return {"$or": [
            {"_id": document["_id"]},
            {"companyId": document["companyId"], "productId": document["productId"]},
        ]}
    if collection == "counters":
        return {"_id": document["_id"]}
    return {"$or": [{"_id": document["_id"]}, {"id": document["id"]}]}


def _identity_matches(collection: str, existing: Mapping, expected: Mapping) -> bool:
    if collection == "users":
        return existing.get("id") == expected["id"] and existing.get("email") == expected["email"]
    if collection == "customer_prices":
        return (
            existing.get("companyId") == expected["companyId"]
            and existing.get("productId") == expected["productId"]
        )
    if collection == "counters":
        return existing.get("_id") == expected["_id"]
    return existing.get("id") == expected["id"]


def _document_fingerprint(document: Mapping) -> str:
    payload = dict(document)
    payload.pop(DEMO_FINGERPRINT_FIELD, None)
    canonical = json.dumps(
        payload,
        ensure_ascii=False,
        allow_nan=False,
        separators=(",", ":"),
        sort_keys=True,
    ).encode("utf-8")
    return sha256(canonical).hexdigest()


def _stored_document_matches_expected(
    collection: str,
    existing: Mapping,
    expected: Mapping,
    passwords: Mapping[str, str],
) -> bool:
    actual = dict(existing)
    actual.pop(DEMO_FINGERPRINT_FIELD, None)
    expected_payload = dict(expected)

    if collection != "users":
        return _strict_equal(actual, expected_payload)

    password_key = expected_payload.pop("_passwordKey", None)
    hashed_password = actual.pop("hashed_password", None)
    if not isinstance(hashed_password, str) or not re.fullmatch(
        r"\$2[aby]\$\d{2}\$[./A-Za-z0-9]{53}",
        hashed_password,
    ):
        return False
    try:
        if not bcrypt.checkpw(
            passwords[password_key].encode("utf-8"),
            hashed_password.encode("utf-8"),
        ):
            return False
    except (KeyError, TypeError, ValueError):
        return False
    return _strict_equal(actual, expected_payload)


async def _require_canonical_ss_tenant(database) -> None:
    matches = await database.tenants.find({
        "$or": [
            {"id": SS_TENANT_ID},
            {"slug": SS_TENANT.slug},
        ]
    }).to_list(length=3)
    if len(matches) != 1:
        raise DemoSeedConflictError(
            "Demo seed requires exactly one canonical S&S tenant from migration 2"
        )

    document = matches[0]
    created_at = document.get("createdAt")
    updated_at = document.get("updatedAt")
    try:
        expected = tenant_to_document(
            SS_TENANT,
            created_at=created_at,
            updated_at=updated_at,
        )
    except (TypeError, ValueError) as exc:
        raise DemoSeedConflictError(
            "Demo seed requires an unmodified active canonical S&S tenant"
        ) from exc
    actual = {key: value for key, value in document.items() if key != "_id"}
    if not _strict_equal(actual, expected):
        raise DemoSeedConflictError(
            "Demo seed requires an unmodified active canonical S&S tenant"
        )


async def _find_matches(database, collection: str, document: Mapping) -> list[dict]:
    return await database[collection].find(_identity_query(collection, document)).to_list(length=3)


def _assert_owned_match(
    collection: str,
    expected: Mapping,
    matches: list[Mapping],
    passwords: Mapping[str, str],
) -> bool:
    if not matches:
        return False
    if len(matches) != 1:
        raise DemoSeedConflictError(
            f"Demo seed conflict in {collection}: multiple documents use the same demo identity"
        )
    existing = matches[0]
    if existing.get("_demoSeed") != DEMO_SEED_VERSION:
        if str(existing.get("_demoSeed", "")).startswith("ordo-demo-"):
            raise DemoSeedConflictError(
                f"Demo seed conflict in {collection}: legacy demo data requires an explicit upgrade"
            )
        raise DemoSeedConflictError(
            f"Demo seed conflict in {collection}: an existing business document uses a demo identity"
        )
    if not _identity_matches(collection, existing, expected):
        raise DemoSeedConflictError(
            f"Demo seed conflict in {collection}: the reserved demo document has another identity"
        )
    stored_fingerprint = existing.get(DEMO_FINGERPRINT_FIELD)
    try:
        actual_fingerprint = _document_fingerprint(existing)
    except (TypeError, ValueError):
        actual_fingerprint = ""
    if (
        not isinstance(stored_fingerprint, str)
        or len(stored_fingerprint) != 64
        or not compare_digest(stored_fingerprint, actual_fingerprint)
    ):
        raise DemoSeedConflictError(
            f"Demo seed conflict in {collection}: a marked demo document is modified or incomplete"
        )
    if not _stored_document_matches_expected(collection, existing, expected, passwords):
        raise DemoSeedConflictError(
            f"Demo seed conflict in {collection}: a marked demo document differs from the manifest"
        )
    return True


def _validate_passwords(passwords: Mapping[str, str]) -> None:
    missing = [key for key in PASSWORD_KEYS if not str(passwords.get(key, "")).strip()]
    if missing:
        raise DemoSeedConfigurationError(
            "Missing demo passwords: " + ", ".join(sorted(missing))
        )


async def seed_demo(
    database,
    *,
    app_env: str,
    target_confirmation: str,
    passwords: Mapping[str, str],
    password_hasher: Callable[[str], str] = hash_demo_password,
    now: datetime | None = None,
) -> dict:
    """Insert only missing demo documents and never overwrite existing data."""

    validate_demo_target(app_env, database.name, target_confirmation)
    _validate_passwords(passwords)
    await _require_canonical_ss_tenant(database)
    manifest = build_demo_manifest(now)
    pending: list[tuple[str, dict]] = []
    unchanged = 0
    per_collection = {name: {"inserted": 0, "unchanged": 0} for name in manifest}

    # Complete the conflict check before the first write.
    for collection, documents in manifest.items():
        for expected in documents:
            matches = await _find_matches(database, collection, expected)
            if _assert_owned_match(collection, expected, matches, passwords):
                unchanged += 1
                per_collection[collection]["unchanged"] += 1
            else:
                pending.append((collection, expected))

    inserted = 0
    for collection, expected in pending:
        document = dict(expected)
        password_key = document.pop("_passwordKey", None)
        if password_key:
            document["hashed_password"] = password_hasher(passwords[password_key])
        document[DEMO_FINGERPRINT_FIELD] = _document_fingerprint(document)
        try:
            await database[collection].insert_one(document)
            matches = await _find_matches(database, collection, expected)
            _assert_owned_match(collection, expected, matches, passwords)
            inserted += 1
            per_collection[collection]["inserted"] += 1
        except DuplicateKeyError:
            # A concurrent identical seed run may have inserted the deterministic _id.
            matches = await _find_matches(database, collection, expected)
            if not _assert_owned_match(collection, expected, matches, passwords):
                raise
            unchanged += 1
            per_collection[collection]["unchanged"] += 1

    return {
        "seedVersion": DEMO_SEED_VERSION,
        "inserted": inserted,
        "unchanged": unchanged,
        "collections": per_collection,
    }
